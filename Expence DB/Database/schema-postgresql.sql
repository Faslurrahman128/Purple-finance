BEGIN;

DROP TABLE IF EXISTS transactions;
DROP TABLE IF EXISTS budget_notification_log;
DROP TABLE IF EXISTS auth_sessions;
DROP TABLE IF EXISTS budgets;
DROP TABLE IF EXISTS payment_methods;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS accounts;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
  user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  profile_image TEXT
);

CREATE TABLE auth_sessions (
  session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE accounts (
  account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  account_name VARCHAR(100) NOT NULL,
  account_type VARCHAR(50) NOT NULL,
  current_balance NUMERIC(12,2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_accounts_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id)
    ON DELETE CASCADE
);

CREATE TABLE categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(user_id) ON DELETE CASCADE,
  category_name VARCHAR(80) NOT NULL
);

CREATE TABLE payment_methods (
  payment_method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(user_id) ON DELETE CASCADE,
  method_name VARCHAR(80) NOT NULL
);

CREATE TABLE user_category_settings (
  user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL REFERENCES categories(category_id) ON DELETE CASCADE,
  custom_name VARCHAR(80),
  hidden BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (user_id, category_id)
);

CREATE TABLE transactions (
  transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  account_id INTEGER NOT NULL,
  category_id INTEGER NOT NULL,
  payment_method_id INTEGER NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  transaction_type VARCHAR(10) NOT NULL
    CHECK (transaction_type IN ('Income', 'Expense')),
  transaction_date DATE NOT NULL,
  description VARCHAR(255),
  CONSTRAINT fk_transactions_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id)
    ON DELETE CASCADE,
  CONSTRAINT fk_transactions_account
    FOREIGN KEY (account_id)
    REFERENCES accounts(account_id),
  CONSTRAINT fk_transactions_category
    FOREIGN KEY (category_id)
    REFERENCES categories(category_id),
  CONSTRAINT fk_transactions_payment_method
    FOREIGN KEY (payment_method_id)
    REFERENCES payment_methods(payment_method_id)
);

CREATE TABLE budgets (
  budget_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  category_id INTEGER NOT NULL,
  budget_amount NUMERIC(12,2) NOT NULL CHECK (budget_amount > 0),
  month_num SMALLINT NOT NULL CHECK (month_num BETWEEN 1 AND 12),
  year_num SMALLINT NOT NULL CHECK (year_num BETWEEN 2000 AND 9999),
  CONSTRAINT fk_budgets_user
    FOREIGN KEY (user_id)
    REFERENCES users(user_id)
    ON DELETE CASCADE,
  CONSTRAINT fk_budgets_category
    FOREIGN KEY (category_id)
    REFERENCES categories(category_id)
);

CREATE TABLE budget_notification_log (
  notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  budget_id INTEGER NOT NULL,
  threshold SMALLINT NOT NULL CHECK (threshold IN (90, 100)),
  spent_amount NUMERIC(12,2) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_budget_notification_budget
    FOREIGN KEY (budget_id)
    REFERENCES budgets(budget_id)
    ON DELETE CASCADE,
  CONSTRAINT uq_budget_notification_threshold UNIQUE (budget_id, threshold)
);

CREATE INDEX idx_accounts_user_id
  ON accounts(user_id);

CREATE INDEX idx_transactions_user_id
  ON transactions(user_id);

CREATE UNIQUE INDEX uq_categories_owner_name
  ON categories (COALESCE(user_id, 0), LOWER(category_name));

CREATE UNIQUE INDEX uq_payment_methods_owner_name
  ON payment_methods (COALESCE(user_id, 0), LOWER(method_name));

CREATE INDEX idx_transactions_account_id
  ON transactions(account_id);

CREATE INDEX idx_transactions_category_id
  ON transactions(category_id);

CREATE INDEX idx_transactions_payment_method_id
  ON transactions(payment_method_id);

CREATE INDEX idx_transactions_date
  ON transactions(transaction_date);

CREATE INDEX idx_budgets_user_id
  ON budgets(user_id);

CREATE INDEX idx_budgets_category_id
  ON budgets(category_id);

