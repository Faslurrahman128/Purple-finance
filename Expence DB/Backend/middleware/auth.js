import { createHash, randomBytes, scrypt as scryptCallback, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';
import { pool } from '../config/db.js';

const scrypt = promisify(scryptCallback);
const COOKIE = 'purple_session';

export async function ensureAuthSchema() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS auth_sessions (
      session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
      token_hash VARCHAR(64) NOT NULL UNIQUE,
      expires_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await pool.query('CREATE INDEX IF NOT EXISTS idx_auth_sessions_expiry ON auth_sessions(expires_at)');
  await pool.query('ALTER TABLE categories ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(user_id) ON DELETE CASCADE');
  await pool.query('ALTER TABLE payment_methods ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(user_id) ON DELETE CASCADE');
  await pool.query('ALTER TABLE categories DROP CONSTRAINT IF EXISTS categories_category_name_key');
  await pool.query('ALTER TABLE payment_methods DROP CONSTRAINT IF EXISTS payment_methods_method_name_key');
  await pool.query('CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_owner_name ON categories (COALESCE(user_id, 0), LOWER(category_name))');
  await pool.query('CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_methods_owner_name ON payment_methods (COALESCE(user_id, 0), LOWER(method_name))');
  await pool.query(`CREATE TABLE IF NOT EXISTS user_category_settings (
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL REFERENCES categories(category_id) ON DELETE CASCADE,
    custom_name VARCHAR(80), hidden BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, category_id)
  )`);
}

export async function hashPassword(password) {
  const salt = randomBytes(16).toString('hex');
  const derived = await scrypt(password, salt, 64);
  return `scrypt$${salt}$${Buffer.from(derived).toString('hex')}`;
}

export async function verifyPassword(password, stored) {
  if (!stored?.startsWith('scrypt$')) return password === stored;
  const [, salt, expectedHex] = stored.split('$');
  const actual = Buffer.from(await scrypt(password, salt, 64));
  const expected = Buffer.from(expectedHex, 'hex');
  return actual.length === expected.length && timingSafeEqual(actual, expected);
}

function tokenHash(token) {
  return createHash('sha256').update(token).digest('hex');
}

function cookies(req) {
  return Object.fromEntries(String(req.headers.cookie || '').split(';').map(item => item.trim().split('=').map(decodeURIComponent)).filter(parts => parts.length === 2));
}

export async function createSession(userId, res) {
  await ensureAuthSchema();
  const token = randomBytes(32).toString('hex');
  const expiresAt = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000);
  await pool.query('INSERT INTO auth_sessions (user_id, token_hash, expires_at) VALUES ($1, $2, $3)', [userId, tokenHash(token), expiresAt]);
  res.cookie(COOKIE, token, { httpOnly: true, sameSite: 'lax', secure: process.env.NODE_ENV === 'production', maxAge: 7 * 24 * 60 * 60 * 1000, path: '/' });
}

export async function destroySession(req, res) {
  const token = cookies(req)[COOKIE];
  if (token) await pool.query('DELETE FROM auth_sessions WHERE token_hash = $1', [tokenHash(token)]);
  res.clearCookie(COOKIE, { httpOnly: true, sameSite: 'lax', secure: process.env.NODE_ENV === 'production', path: '/' });
}

export async function requireAuth(req, res, next) {
  try {
    await ensureAuthSchema();
    const token = cookies(req)[COOKIE];
    if (!token) return res.status(401).json({ message: 'Please sign in to continue' });
    const { rows } = await pool.query(`SELECT u.user_id, u.name, u.email FROM auth_sessions s JOIN users u ON u.user_id=s.user_id WHERE s.token_hash=$1 AND s.expires_at > CURRENT_TIMESTAMP`, [tokenHash(token)]);
    if (!rows.length) return res.status(401).json({ message: 'Your session has expired. Please sign in again.' });
    req.user = rows[0];
    next();
  } catch (error) { next(error); }
}
