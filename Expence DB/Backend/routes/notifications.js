import { Router } from 'express';
import nodemailer from 'nodemailer';
import { pool } from '../config/db.js';

const router = Router();

function emailConfigured() {
  return Boolean(process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASSWORD && process.env.SMTP_FROM);
}

function transporter() {
  return nodemailer.createTransport({
    host: process.env.SMTP_HOST,
    port: Number(process.env.SMTP_PORT || 587),
    secure: String(process.env.SMTP_SECURE).toLowerCase() === 'true',
    auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASSWORD }
  });
}

async function ensureNotificationLog() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS budget_notification_log (
      notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      budget_id INTEGER NOT NULL REFERENCES budgets(budget_id) ON DELETE CASCADE,
      threshold SMALLINT NOT NULL CHECK (threshold IN (90, 100)),
      spent_amount NUMERIC(12,2) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (budget_id, threshold)
    )
  `);
}

router.post('/budget-check', async (req, res, next) => {
  const userId = req.user.user_id;

  try {
    await ensureNotificationLog();
    const { rows } = await pool.query(`
      SELECT b.budget_id, b.budget_amount, b.month_num, b.year_num,
             COALESCE(ucs.custom_name, c.category_name) AS category_name, u.email,
             COALESCE(SUM(CASE WHEN t.transaction_type = 'Expense' THEN t.amount ELSE 0 END), 0) AS spent
      FROM budgets b
      JOIN categories c ON c.category_id = b.category_id
      LEFT JOIN user_category_settings ucs ON ucs.category_id = c.category_id AND ucs.user_id = b.user_id
      JOIN users u ON u.user_id = b.user_id
      LEFT JOIN transactions t
        ON t.user_id = b.user_id
       AND t.category_id = b.category_id
       AND EXTRACT(MONTH FROM t.transaction_date) = b.month_num
       AND EXTRACT(YEAR FROM t.transaction_date) = b.year_num
      WHERE b.user_id = $1
      GROUP BY b.budget_id, c.category_name, ucs.custom_name, u.email
      HAVING COALESCE(SUM(CASE WHEN t.transaction_type = 'Expense' THEN t.amount ELSE 0 END), 0) >= b.budget_amount * 0.9
      ORDER BY b.year_num DESC, b.month_num DESC, b.budget_id DESC
    `, [userId]);

    const configured = emailConfigured();
    const mailer = configured ? transporter() : null;
    let emailsSent = 0;
    const alerts = [];

    for (const row of rows) {
      const spent = Number(row.spent);
      const budget = Number(row.budget_amount);
      const threshold = spent >= budget ? 100 : 90;
      const remaining = Math.max(0, budget - spent);
      let isNew = true;
      if (configured) {
        const inserted = await pool.query(`
          INSERT INTO budget_notification_log (budget_id, threshold, spent_amount)
          VALUES ($1, $2, $3)
          ON CONFLICT (budget_id, threshold) DO NOTHING
          RETURNING notification_id
        `, [row.budget_id, threshold, spent]);
        isNew = inserted.rowCount > 0;
      }
      alerts.push({
        budget_id: row.budget_id,
        category_name: row.category_name,
        budget_amount: budget,
        spent,
        remaining,
        threshold,
        is_new: isNew
      });

      if (isNew && mailer && row.email) {
        try {
          await mailer.sendMail({
            from: process.env.SMTP_FROM,
            to: row.email,
            subject: `${row.category_name} budget ${threshold === 100 ? 'limit reached' : 'warning'}`,
            text: `Your ${row.category_name} budget is Rs ${budget.toFixed(2)}. You have spent Rs ${spent.toFixed(2)} and have Rs ${remaining.toFixed(2)} remaining.`,
            html: `<h2>${row.category_name} budget ${threshold === 100 ? 'limit reached' : 'warning'}</h2><p>Budget: <strong>Rs ${budget.toFixed(2)}</strong></p><p>Spent: <strong>Rs ${spent.toFixed(2)}</strong></p><p>Remaining: <strong>Rs ${remaining.toFixed(2)}</strong></p>`
          });
          emailsSent += 1;
        } catch (error) {
          await pool.query('DELETE FROM budget_notification_log WHERE budget_id = $1 AND threshold = $2', [row.budget_id, threshold]);
          console.error('Budget email failed:', error.message);
        }
      }
    }

    res.json({ alerts, email_configured: configured, emails_sent: emailsSent });
  } catch (error) {
    next(error);
  }
});

export default router;
